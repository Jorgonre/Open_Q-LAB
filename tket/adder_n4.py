from pytket import Circuit
from pytket.extensions.qiskit import AerBackend

circ = Circuit(4)

circ.X(0)
circ.X(1)
circ.H(3)
circ.CX(2, 3)
circ.T(0)
circ.T(1)
circ.T(2)
circ.S(3)
circ.S(3)
circ.S(3)
circ.T(3)
circ.CX(0, 1)
circ.CX(2, 3)
circ.CX(3, 0)
circ.CX(1, 2)
circ.CX(0, 1)
circ.CX(2, 3)
circ.S(0)
circ.S(0)
circ.S(0)
circ.T(0)
circ.S(1)
circ.S(1)
circ.S(1)
circ.T(1)
circ.S(2)
circ.S(2)
circ.S(2)
circ.T(2)
circ.T(3)
circ.CX(0, 1)
circ.CX(2, 3)
circ.S(3)
circ.CX(3, 0)
circ.H(3)
circ.measure_all()

print("Circuito:")
print(circ)

backend = AerBackend()
compiled = backend.get_compiled_circuit(circ)
result = backend.run_circuit(compiled, n_shots=1024)

print("\nResultados:")
print(result.get_counts())
